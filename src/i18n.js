export const LANGS = Object.keys(STR);
let lang = 'en';
const listeners = [];

export function initLang(saved, sdkLocale) {
  const fromLocale = (sdkLocale || '').slice(0, 2).toLowerCase();
  lang = STR[saved] ? saved : STR[fromLocale] ? fromLocale : 'en';
}
export function getLang() { return lang; }
export function setLang(l) { if (STR[l]) { lang = l; listeners.forEach((f) => f(l)); } }
export function nextLang() { setLang(LANGS[(LANGS.indexOf(lang) + 1) % LANGS.length]); }
export function onLangChange(f) { listeners.push(f); }

export function t(key, vars) {
  let s = (STR[lang] && STR[lang][key]) ?? STR.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replace(`{${k}}`, vars[k]);
  return s;
}
