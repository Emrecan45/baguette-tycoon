import { chromium } from 'playwright';
import { createServer } from 'vite';
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { recordingPlugin } from './recording-plugin.mjs';

const server = await createServer({ plugins: [recordingPlugin()], cacheDir: 'node_modules/.vite-record-smoke', server: { host: '127.0.0.1', port: 5191, strictPort: true }, logLevel: 'error' });
await (await import('node:fs/promises')).mkdir('tmp/marketing', { recursive: true });
await server.listen();
const browser = await chromium.launch({ channel: 'chrome', headless: false, args: ['--enable-gpu', '--use-angle=d3d11'] });
const checks = {};
try {
  const context = await browser.newContext({ viewport: { width: 960, height: 540 }, deviceScaleFactor: 2 });
  await context.route('https://**/*', route => route.fulfill({ status: 200, body: '' }));
  const page = await context.newPage();
  await page.routeWebSocket(/.*/, ws => ws.close());
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.addInitScript(() => {
    localStorage.setItem('baguette-tycoon-v3', '{"money":12345,"unlockIndex":1}');
    window.__rafCount = 0;
    const request = requestAnimationFrame.bind(window);
    window.requestAnimationFrame = callback => { window.__rafCount++; return request(callback); };
  });
  await page.goto('http://127.0.0.1:5191/?debug=2&nointro&record&shot&ts=999', { waitUntil: 'networkidle' });
  await page.waitForFunction(() => window.bt?.record?.ready, null, { polling: 100 });
  const image = `data:image/png;base64,${(await readFile('marketing/covers/cover-landscape-1920x1080.png')).toString('base64')}`;
  await page.evaluate(image => bt.record.prepare(960, 540, image), image);
  const before = await page.evaluate(() => bt.record.metrics());
  await page.waitForTimeout(250);
  assert.equal(await page.evaluate(() => bt.record.metrics().simulationTime), before.simulationTime);
  const after = await page.evaluate(() => { for (let i = 0; i < 12; i++) renderFrame(); return { metrics: bt.record.metrics(), raf: window.__rafCount, save: localStorage.getItem('baguette-tycoon-v3'), canvas: [document.getElementById('game').width, document.getElementById('game').height] }; });
  assert.ok(Math.abs(after.metrics.simulationTime - before.simulationTime - 12 / 60) < 1e-10);
  assert.equal(after.raf, 0);
  assert.equal(after.metrics.pixelRatio, 1);
  assert.deepEqual(after.canvas, [960, 540]);
  assert.equal(after.save, '{"money":12345,"unlockIndex":1}');
  checks.record = { frozenWithoutCalls: true, twelveStepsSeconds: after.metrics.simulationTime - before.simulationTime, rafCalls: after.raf, pixelRatio: after.metrics.pixelRatio, canvas: after.canvas, saveUntouched: true, ignoresTs999: true };
  await page.close();
  const normal = await context.newPage();
  await normal.routeWebSocket(/.*/, ws => ws.close());
  normal.on('pageerror', e => errors.push(e.message));
  await normal.goto('http://127.0.0.1:5191/?debug=2&nointro', { waitUntil: 'networkidle' });
  await normal.waitForFunction(() => window.bt);
  const initial = await normal.evaluate(() => ({ time: bt.game().time, position: bt.player.pos.toArray(), hasRecord: !!bt.record || typeof window.renderFrame === 'function' }));
  assert.equal(initial.hasRecord, false);
  await normal.keyboard.down('KeyW'); await normal.waitForTimeout(500); await normal.keyboard.up('KeyW');
  const next = await normal.evaluate(() => ({ time: bt.game().time, position: bt.player.pos.toArray(), canvas: [document.getElementById('game').width, document.getElementById('game').height] }));
  assert.ok(next.time > initial.time);
  assert.ok(next.position[2] > initial.position[2] + .2);
  await normal.setViewportSize({ width: 800, height: 600 });
  await normal.waitForTimeout(200);
  assert.equal(await normal.evaluate(() => getComputedStyle(document.getElementById('game')).width), '800px');
  checks.normal = { automaticClock: true, keyboardMovesPlayer: true, resize: true, noRecordingGlobal: true };
  assert.deepEqual(errors, []);
  await context.close();
  await writeFile('tmp/marketing/runtime-checks.json', JSON.stringify(checks, null, 2));
  console.log(checks);
} finally { await browser.close(); await server.close(); }
